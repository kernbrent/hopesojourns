THE LIFE GOD GIVES

Read Revelation 22:1–5. Passage summary: John’s vision includes life flowing from God’s throne, the tree of life, the removal of the curse, and God’s servants living in His presence. Their future includes worshipful service and an enduring share in His reign.

The river and tree present life as God’s gift. The throne remains central, reminding us that the goodness of this future rests on who rules it. The vision answers the idea that eternity would be empty or purposeless: God’s people belong, serve, and share in life with Him.

Some details invite questions the passage does not fully answer. We need not invent the daily schedule of eternity or explain exactly how each image will be realized. The clear promises are enough to sustain worship: God gives life, the curse ends, and His people live in His presence.


TALKING POINTS

Eternity has purpose. Service to God belongs within joy and freedom, rather than exhaustion or insecurity.

The promise of seeing God’s face expresses the depth of relationship toward which the vision points. Let that shape our longing more than speculation about possessions or status.

The good character we practiced during the Feast remains relevant when we return home. Gratitude, hospitality, faithfulness, and service express our present allegiance to Jesus.


GROUP QUESTIONS

1. What in this passage suggests fullness of life rather than boredom or inactivity?

2. How do the throne, river, and tree help you understand the source of life in this vision?

3. What have these eight days taught you about the character of the God with whom we hope to live forever?

4. What is one practice from the Feast that you want to continue after returning home?


CARRY THE HOPE HOME

Ask each person to choose one realistic practice for the next month: a regular time in Scripture, an act of service each week, a shared meal with someone who needs welcome, or a step toward peace. Invite volunteers to tell a trusted friend what they have chosen and ask for encouragement. This is a response to God’s grace and promise, not a way to earn eternal life.


