Read Revelation 21:4–7. Passage summary: God removes the suffering associated with the former order, promises to make things new, offers life freely, and describes the inheritance and relationship of those who overcome.

The promise reaches both the great enemy of death and the intimate experience of tears. God’s victory does not treat human sorrow as a minor detail. The future He announces is one in which the causes of grief no longer have the last word.

Give this promise time to be heard. Some people may immediately think of a loved one, a painful season, or a fear they rarely voice. A leader need not supply an explanation for every loss. The passage offers a reason to trust God with what we cannot repair ourselves.


TALKING POINTS

Eternity is enduring life in a world where death and the former suffering have been removed. It is more than an extension of our present conditions.

God’s declaration of renewal invites confidence in His action. We do not create this future through our own strength.

The promise of inheritance is relational: God claims His people as His own. Talk about trust and faithful belonging rather than earning a place through flawless performance.

The vision follows judgment in the wider narrative of Revelation. Acknowledge God’s righteous judgment when needed, while keeping this gathering focused on the promised life with Him.


GROUP QUESTIONS

1. Which promise in these verses brings you the deepest comfort? You may answer generally or pass.

2. What is the difference between a future with less suffering and the future described here?

3. How can we offer this hope to a grieving person without rushing or minimizing their grief?

4. What does belonging to God add to our understanding of eternity beyond simply living forever?


QUIET REFLECTION

Allow two or three minutes of silence. Invite participants to write privately about one sorrow they entrust to God and one promise they want to carry home. Do not collect these notes or require anyone to read them aloud.


A BRIDGE TO THE FINAL READING

Say in your own words: We have considered what will be removed. Now we will consider the life and relationship that will fill that future. God’s promise gives us something to look forward to, as well as something from which to be delivered.


